"""Structural executor ports; implementations remain in owning modules."""
from typing import Any, ContextManager, Protocol


class WorkHandler(Protocol):
    kind: str
    atomic_execution: bool
    # Optional implementation flag: terminal receipt is committed by execute.
    # Older handlers without it retain common completion behavior.

    def target_key(self, payload: dict[str, Any]) -> str: ...
    def capture_snapshot(self, envelope: dict[str, Any]) -> tuple[dict, dict]: ...
    def execute(self, envelope: dict[str, Any]) -> tuple[dict, list[dict]]: ...


class ReceiptRepository(Protocol):
    def claim_transaction(self) -> ContextManager: ...
    def locked_job(self, job_id: str) -> Any: ...
    def get(self, job_id: str) -> Any: ...
    def conflicting_job(self, job_id, work_kind, target_key, payload, source_snapshot) -> Any: ...
    def restart(self, receipt) -> Any: ...
    def create_claim(self, **fields) -> tuple[Any, bool]: ...
    def complete(self, receipt, *, result, followups) -> Any: ...
    def fail(self, receipt, *, code, message, retryable, result=None) -> Any: ...


class PlanDomainAdapter(Protocol):
    """Checks/result translation only; no submission storage or publication."""

    def validate(self, plan, submission) -> Any: ...
    def source_guard(self, plan, submission) -> ContextManager: ...
    def report(self, plan, submission, response) -> Any: ...


class BoundInputPlanAdapter(PlanDomainAdapter, Protocol):
    """Additional v2 ports; compilation may persist a domain-owned manifest.

    No direct transport or common journal writes are permitted in these ports.
    """
    def resolve_input(self, plan, submission, binding, *, producer_job_id=None) -> Any: ...
    def compile_command(self, plan, submission, step, artifact) -> dict: ...
    def validate_compiled_command(self, plan, submission, step, payload, artifact) -> Any: ...
